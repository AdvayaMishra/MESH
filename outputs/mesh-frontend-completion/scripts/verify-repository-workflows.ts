import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
import { tenants } from "../lib/api/mock";
const w = () => useWorkspace.getState();
w().switchOrg("lumen");
const repo = w().repos.find(r => r.authorized)!;
useUI.setState({role: "hr"});
assert.equal(w().setRepositoryAuthorization(repo.name, false).ok, false);
useUI.setState({role: "owner"});
assert.equal(w().setRepositoryAuthorization(repo.name, false).ok, true);
assert.equal(w().repos.find(r => r.name === repo.name)?.authorized, false);
assert.equal(w().setRepositoryAuthorization(repo.name, false).ok, false);
const ownerId = tenants.lumen.roleUsers.owner;
const pr = w().pullRequests.find(p => p.status !== "Merged" && p.author !== ownerId)!;
useUI.setState({role: "junior-dev"});
assert.equal(w().reviewPullRequest(pr.id, "Approved", "Reviewed code and tests").ok, false);
useUI.setState({role: "owner"});
assert.equal(w().reviewPullRequest(pr.id, "Changes requested", "short").ok, false);
assert.equal(w().reviewPullRequest(pr.id, "Changes requested", "Please correct error handling").ok, true);
assert.equal(w().prReviews[pr.id][0].note, "Please correct error handling");
assert.equal(w().mergePullRequest(pr.id, "Reviewed and verified").ok, false);
assert.equal(w().reviewPullRequest(pr.id, "Approved", "Changes were reviewed").ok, true);
assert.equal(w().pullRequests.find(p => p.id === pr.id)?.status, "Approved");
w().switchOrg("northwind");
assert.equal(w().repos.some(r => r.name === repo.name), false);
assert.equal(w().reviewPullRequest(pr.id, "Approved", "Reviewed code and tests").ok, false);
w().switchOrg("lumen");
assert.equal(w().repos.find(r => r.name === repo.name)?.authorized, false);
assert.equal(w().prReviews[pr.id].length, 2);
console.log("Repository workflow: 15 checks passed");
