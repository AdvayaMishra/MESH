/** Logic-only regression suite; when dependencies are missing run with the documented test shims. */
import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
import { tenants } from "../lib/api/mock";
const w = () => useWorkspace.getState();
const as = (role: "owner" | "hr" | "senior-dev" | "junior-dev" | "security-analyst") => useUI.setState({ role });
w().switchOrg("lumen");
const finding = w().findings[0];
const target = tenants.lumen.employees.find(e => e.appRole === "security-analyst")!;
as("hr");
assert.equal(w().assignFinding(finding.id, target.id).ok, false);
assert.equal(w().setFindingStatus(finding.id, "Fixed").ok, false);
const incident = w().incidents.find(i => i.status !== "Resolved")!;
assert.equal(w().setIncidentStatus(incident.id, "Contained").ok, false);
assert.equal(w().approveIncidentResponse(incident.id, "block", "Block", "A sufficient reason").ok, false);
as("senior-dev");
assert.equal(w().assignFinding(finding.id, "not-an-employee").ok, false);
assert.equal(w().assignFinding(finding.id, target.id).ok, true);
assert.equal(w().findings.find(f => f.id === finding.id)?.assignee, target.id);
assert.equal(w().setFindingStatus(finding.id, "Fixed").ok, true);
assert.equal(w().findings.find(f => f.id === finding.id)?.status, "Fixed");
assert.equal(w().audit[0].result, "Simulated");
as("security-analyst");
assert.equal(w().setIncidentStatus(incident.id, "Resolved", 50).ok, true);
assert.equal(w().setIncidentStatus(incident.id, "Open").ok, false);
assert.equal(w().audit[0].module, "VADER");
w().switchOrg("northwind");
assert.equal(w().assignFinding(finding.id, target.id).ok, false);
w().switchOrg("lumen");
assert.equal(w().findings.find(f => f.id === finding.id)?.assignee, target.id);
console.log("Security workflow: 15 checks passed");
