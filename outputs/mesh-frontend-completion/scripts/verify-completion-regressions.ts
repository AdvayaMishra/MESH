import { visibleAudit } from "../lib/audit-visibility";
import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
import { tenants } from "../lib/api/mock";
import { notificationFromAudit, visibleNotification } from "../lib/notifications";
import { usePreferences, preferenceKey } from "../stores/preferences-store";
const w = () => useWorkspace.getState();
w().switchOrg("lumen");
const task = w().tasks[0];
const n = { id: "notice", title: "Review", body: "Internal", href: "/people/directory", read: false, at: "2026-10-27", module: "People" as const, tone: "mint" as const };
assert.equal(visibleNotification(n, "junior-dev"), false);
assert.equal(visibleNotification(n, "hr"), true);
assert.equal(visibleNotification({ ...n, audience: ["other"] }, "hr", "me"), false);
assert.equal(visibleNotification({ ...n, href: "/people/complaints" }, "hr"), false);
useUI.setState({ role: "hr" });
assert.equal(w().updateTask(task.id, { title: "Forbidden update" }).ok, false);
assert.equal(w().setTaskStatus(task.id, "Done").ok, false);
assert.equal(w().assignTask(task.id, tenants.lumen.roleUsers.hr).ok, false);
useUI.setState({ role: "senior-dev" });
assert.equal(w().updateTask(task.id, { points: -1 }).ok, false);
assert.equal(w().updateTask(task.id, { due: "2027-02-30" }).ok, false);
assert.equal(w().assignTask(task.id, tenants.northwind.roleUsers["junior-dev"]).ok, false);
assert.equal(w().addComment(task.id, tenants.lumen.roleUsers.owner, "Impersonation").ok, false);
assert.equal(w().addComment(task.id, tenants.lumen.roleUsers["senior-dev"], "Reviewed this task").ok, true);
assert.equal(w().updateTask(task.id, { title: "Validated task update" }).ok, true);
assert.equal(w().audit[0].target, task.id);
const prefs = usePreferences.getState();
assert.equal(prefs.saveProfile("lumen", "owner", { name: "Demo Owner", email: "demo@example.invalid", role: "Lead" }), null);
assert.equal(usePreferences.getState().profiles[preferenceKey("northwind", "owner")], undefined);
assert.equal(usePreferences.getState().profiles[preferenceKey("lumen", "hr")], undefined);
assert.notEqual(prefs.saveProfile("lumen", "owner", { name: "", email: "invalid", role: "" }), null);
console.log("Completion regressions: 18 checks passed against real libraries");

const privateAudit = { id: "audit-private", actor: "Person", action: "Internal note added", target: "C-999", module: "People" as const, result: "Simulated" as const, at: "2026-10-28", ip: "Demo" };
assert.equal(visibleAudit(privateAudit, "owner", ["C-999"]), false);
assert.equal(visibleAudit({...privateAudit, target:"employee"}, "security-analyst", []), false);
assert.equal(visibleAudit({...privateAudit, action:"Complaint submitted", target:"unknown"}, "owner", []), false);
console.log("Confidential audit redaction: 3 checks passed");

assert.equal(notificationFromAudit(privateAudit,tenants.lumen.roleUsers,["C-999"]),null);
const taskNotice=notificationFromAudit({...privateAudit,action:"Created task (simulated)",target:"TASK-1",module:"DevTrack"},tenants.lumen.roleUsers,[]);
assert.ok(taskNotice?.audience?.includes(tenants.lumen.roleUsers["junior-dev"]));
assert.equal(taskNotice?.audience?.includes(tenants.lumen.roleUsers.hr),false);
console.log("Business notification scope and private-case exclusion: 3 checks passed");

const personaPrefs=usePreferences.getState();
const previousJunior=tenants.lumen.roleUsers["junior-dev"];
const nextJunior=tenants.lumen.employees.find((e)=>e.appRole==="junior-dev"&&e.id!==previousJunior)!;
personaPrefs.saveProfile("lumen","junior-dev",{name:"Previous private profile",email:"previous@example.invalid",role:"Engineer"});
personaPrefs.savePhoto("lumen","junior-dev","data:image/png;base64,AAAA");
personaPrefs.saveSupportDraft("lumen","junior-dev","A private draft for the previous employee");
personaPrefs.saveProfile("lumen","junior-dev",{name:"Invited profile",email:"invited@example.invalid",role:"Engineer"},nextJunior.id);
personaPrefs.selectPersona("lumen","junior-dev",nextJunior.id);
assert.equal(usePreferences.getState().profiles[preferenceKey("lumen","junior-dev")].name,"Invited profile");
assert.equal(usePreferences.getState().photos[preferenceKey("lumen","junior-dev")],undefined);
assert.equal(usePreferences.getState().supportDrafts[preferenceKey("lumen","junior-dev")],undefined);
personaPrefs.selectPersona("lumen","junior-dev",previousJunior);
assert.equal(usePreferences.getState().profiles[preferenceKey("lumen","junior-dev")].name,"Previous private profile");
assert.equal(usePreferences.getState().photos[preferenceKey("lumen","junior-dev")],"data:image/png;base64,AAAA");
console.log("Same-role employee identity isolation: 5 checks passed");
