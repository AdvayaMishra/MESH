import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { getDataset } from "../lib/api/use-dataset";
import { useUI } from "../stores/ui-store";
const w = () => useWorkspace.getState();
w().switchOrg("lumen"); useUI.setState({ role: "hr" });
assert.equal(w().preparePayroll().ok, false);
for (const discrepancy of getDataset("lumen").payrollSummary.discrepancies) assert.equal(w().reviewPayroll(discrepancy.id, "Reviewed").ok, true);
assert.equal(w().preparePayroll().ok, true);
assert.equal(w().approvePayroll().ok, false);
useUI.setState({ role: "owner" });
assert.equal(w().approvePayroll().ok, true);
assert.equal(w().approvePayroll().ok, false);
const project = w().projects.find((p) => p.status === "Active")!;
const employee = getDataset("lumen").employees.find((e) => !project.members.includes(e.id) && e.status === "Active" && e.id !== project.lead)!;
assert.equal(w().setProjectMember(project.id, employee.id, true).ok, true);
assert.equal(getDataset("lumen").employeeById(employee.id)?.projects.includes(project.id), true);
assert.equal(w().setProjectMember(project.id, employee.id, true).ok, false);
assert.equal(w().setProjectMember(project.id, employee.id, false).ok, true);
assert.equal(getDataset("lumen").employeeById(employee.id)?.projects.includes(project.id), false);
assert.equal(w().setProjectMember(project.id, project.lead, false).ok, false);
useUI.setState({ role: "junior-dev" });
assert.equal(w().setProjectMember(project.id, employee.id, true).ok, false);
w().switchOrg("northwind"); assert.equal(w().payrollRun, null);
console.log("Resource allocation and payroll checks passed");
