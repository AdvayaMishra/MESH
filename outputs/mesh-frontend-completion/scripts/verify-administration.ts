import { strict as assert } from "node:assert";
import { useAdministration, administration } from "../stores/admin-store";
import { useTenant } from "../stores/tenant-store";
import { useUI } from "../stores/ui-store";
const a = () => useAdministration.getState();
useTenant.setState({ orgId: "lumen" }); useUI.setState({ role: "owner" });
assert.equal(a().saveOrganization("Updated Lumen", "lumen.example").ok, true);
assert.equal(administration("lumen").org.name, "Updated Lumen");
assert.notEqual(administration("northwind").org.name, "Updated Lumen");
assert.equal(a().setBudget("Engineering", 12000).ok, true);
assert.equal(a().setBudget("Engineering", -1).ok, false);
assert.equal(administration("northwind").budgets.Engineering, undefined);
const input = { name: "New Demo Employee", email: "new@example.invalid", title: "Engineer", department: "Engineering" as const, appRole: "junior-dev" as const };
assert.equal(a().addEmployee(input).ok, true);
assert.equal(a().addEmployee(input).ok, false);
const employee = administration("lumen").employees.find((e) => e.email === input.email)!;
assert.equal(employee.trustScore, 20);
assert.equal(employee.status, "Onboarding");
assert.equal(a().updateEmployee(employee.id, { department: "Security", appRole: "security-analyst", status: "Active" }).ok, true);
useUI.setState({ role: "hr" });
assert.equal(a().saveOrganization("Forbidden", "example.test").ok, false);
assert.equal(a().setBudget("Engineering", 100).ok, false);
assert.equal(a().updateEmployee(employee.id, { department: "Security", appRole: "senior-dev", status: "Active" }).ok, false);
useTenant.setState({ orgId: "northwind" });
assert.equal(a().updateEmployee(employee.id, { department: "Security", appRole: "security-analyst", status: "Active" }).ok, false);
assert.equal(administration("lumen").audit.length, 4);
console.log("Administration: 16 checks passed");

useTenant.setState({ orgId: "lumen" }); useUI.setState({ role: "hr" });
assert.equal(a().proposeLifecycle(employee.id, "offboarding").ok, true);
const plan = administration("lumen").plans[0];
assert.equal(a().transitionLifecycle(plan.id, "approve").ok, false);
assert.equal(a().transitionLifecycle(plan.id, "execute").ok, false);
useUI.setState({ role: "owner" });
assert.equal(a().transitionLifecycle(plan.id, "approve").ok, true);
assert.equal(a().transitionLifecycle(plan.id, "approve").ok, false);
assert.equal(a().transitionLifecycle(plan.id, "execute").ok, true);
assert.equal(administration("lumen").employees.find((e) => e.id === employee.id)?.status, "Offboarding");
assert.equal(a().transitionLifecycle(plan.id, "reverse").ok, true);
assert.equal(administration("lumen").employees.find((e) => e.id === employee.id)?.status, "Active");
assert.equal(a().transitionLifecycle(plan.id, "reverse").ok, false);
console.log("Lifecycle: 10 checks passed");

useTenant.setState({ orgId: "lumen" });useUI.setState({role:"owner"});
assert.equal(a().setBudget("Engineering",0.29).ok,true);
assert.equal(a().setBudget("Engineering",0.291).ok,false);
console.log("Budget cent validation: 2 checks passed");
