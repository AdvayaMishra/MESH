import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
const w = () => useWorkspace.getState();
w().switchOrg("lumen");
useUI.setState({role: "junior-dev"});
assert.equal(w().createSprint("Sprint Test", "2027-01-01", "2027-01-14").ok, false);
useUI.setState({role: "senior-dev"});
assert.equal(w().createSprint("Sprint Test", "2027-02-30", "2027-03-14").ok, false);
assert.equal(w().createSprint("Sprint Test", "2027-02-02", "2027-01-01").ok, false);
assert.equal(w().createSprint("Sprint Test", "2027-01-01", "2027-01-14").ok, true);
assert.equal(w().createSprint("sprint test", "2027-01-01", "2027-01-14").ok, false);
assert.equal(w().setSprintStatus("Sprint Test", "Active").ok, false);
const active = w().sprints.find(s => s.status === "Active")!;
assert.equal(w().setSprintStatus(active.id, "Completed").ok, true);
assert.equal(w().setSprintStatus("Sprint Test", "Active").ok, true);
assert.equal(w().setSprintStatus("Sprint Test", "Completed").ok, true);
assert.equal(w().setSprintStatus("Sprint Test", "Active").ok, false);
w().switchOrg("northwind");
assert.equal(w().sprints.some(s => s.id === "Sprint Test"), false);
w().switchOrg("lumen");
assert.equal(w().sprints.find(s => s.id === "Sprint Test")?.status, "Completed");
console.log("Sprint workflow: 12 checks passed");
