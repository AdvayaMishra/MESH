import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
import { getDataset } from "../lib/api/use-dataset";
import { usePreferences } from "../stores/preferences-store";
const w = () => useWorkspace.getState();
w().switchOrg("lumen"); useUI.setState({ role: "owner" });
const project = w().projects[0];
const task = w().tasks[0];
assert.equal(w().updateTask(task.id, { title: "Current adapter task title" }).ok, true);
assert.equal(getDataset("lumen").tasks.find((v) => v.id === task.id)?.title, "Current adapter task title");
const record = w().idSubmissions.find((v) => v.status === "Pending review")!;
assert.equal(w().decideId(record.id, "Approved", "Reviewed demo evidence").ok, true);
assert.equal(getDataset("lumen").employeeById(record.employee)?.verification, "Verified");
const repo = w().repos.find((v) => v.authorized)!;
assert.equal(w().completeDemoScan(repo.name, "SIM-test-run").ok, true);
assert.equal(w().completeDemoScan(repo.name, "SIM-test-run").ok, false);
assert.equal(getDataset("lumen").scanHistory[0].id, "SIM-test-run");
assert.equal(w().setRepositoryAuthorization(repo.name, false).ok, true);
assert.equal(w().completeDemoScan(repo.name, "SIM-not-authorized").ok, false);
w().switchOrg("northwind");
assert.equal(getDataset("northwind").scanHistory.some((v) => v.id === "SIM-test-run"), false);
assert.equal(getDataset("northwind").tasks.some((v) => v.title === "Current adapter task title"), false);
w().switchOrg("lumen");
assert.equal(w().tasks.find((v) => v.id === task.id)?.title, "Current adapter task title");
assert.equal(getDataset("lumen").projectById(project.id)?.id, project.id);
const persona = getDataset("lumen").employees.find((v) => v.appRole === "junior-dev")!;
usePreferences.getState().selectPersona("lumen", "junior-dev", persona.id);
assert.equal(getDataset("lumen").roleUsers["junior-dev"], persona.id);
assert.throws(() => usePreferences.getState().selectPersona("northwind", "junior-dev", persona.id));
console.log("Second audit: 15 checks passed");

assert.equal(getDataset("lumen").orgKpis.totalEmployees,getDataset("lumen").employees.length);
assert.equal(getDataset("lumen").orgKpis.activeProjects,getDataset("lumen").projects.filter((p)=>p.status==="Active"||p.status==="At risk").length);
console.log("Cross-screen KPI consistency: 2 checks passed");
