import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
import { tenants } from "../lib/api/mock";
const w = () => useWorkspace.getState();
w().switchOrg("lumen");
const project = w().projects.find(p => ["Active", "At risk"].includes(p.status))!;
const developer = tenants.lumen.employees.find(e => e.appRole === "junior-dev")!;
const task = { id: "test-id", key: "TEST-UNIQUE", title: "New demo task", description: "Demo", status: "To do" as const, priority: "Medium" as const, assignee: developer.id, projectId: project.id, points: 3, labels: [], sprint: "Backlog", due: "2027-01-01", comments: [] };
useUI.setState({ role: "hr" });
assert.equal(w().addTask(task).ok, false);
useUI.setState({ role: "junior-dev" });
assert.equal(w().addTask({ ...task, assignee: "missing" }).ok, false);
assert.equal(w().addTask(task).ok, true);
assert.equal(w().addTask(task).ok, false);
assert.equal(w().deleteTask(task.id).ok, false);
w().switchOrg("northwind");
assert.equal(w().tasks.some(t => t.id === task.id), false);
w().switchOrg("lumen");
assert.equal(w().tasks.some(t => t.id === task.id), true);
useUI.setState({ role: "senior-dev" });
const linked = w().tasks.find(t => w().pullRequests.some(pr => pr.taskKey === t.key));
if (linked) assert.equal(w().deleteTask(linked.id).ok, false);
assert.equal(w().deleteTask(task.id).ok, true);
assert.equal(w().tasks.some(t => t.id === task.id), false);
assert.equal(w().audit[0].result, "Simulated");
console.log("Task workflow: checks passed");
