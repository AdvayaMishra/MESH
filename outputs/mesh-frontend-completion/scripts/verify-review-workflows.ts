import { strict as assert } from "node:assert";
import { useWorkspace } from "../stores/workspace-store";
import { useUI } from "../stores/ui-store";
const w = () => useWorkspace.getState();
w().switchOrg("lumen");
const submission = w().idSubmissions.find(x => x.status === "Pending review")!;
useUI.setState({ role: "junior-dev" });
assert.equal(w().decideId(submission.id, "Approved", "reviewed").ok, false);
useUI.setState({ role: "hr" });
assert.equal(w().decideId(submission.id, "Needs resubmission", "").ok, false);
assert.equal(w().decideId(submission.id, "Needs resubmission", "Please provide a clearer document").ok, true);
assert.equal(w().idSubmissions.find(x => x.id === submission.id)?.history[0].note, "Please provide a clearer document");
assert.equal(w().decideId(submission.id, "Approved", "").ok, false);
const project = w().projects.find(p => p.status === "Awaiting approval")!;
assert.equal(w().setProjectStatus(project.id, "Active", "").ok, false);
useUI.setState({ role: "owner" });
assert.equal(w().setProjectStatus(project.id, "Rejected", "").ok, false);
assert.equal(w().setProjectStatus(project.id, "Rejected", "Not within budget").ok, true);
assert.equal(w().approvalHistory[project.id][0].note, "Not within budget");
assert.equal(w().setProjectStatus(project.id, "Active", "").ok, false);
w().switchOrg("northwind");
assert.equal(w().decideId(submission.id, "Approved", "").ok, false);
w().switchOrg("lumen");
assert.equal(w().idSubmissions.find(x => x.id === submission.id)?.status, "Needs resubmission");
console.log("Review workflow: 12 checks passed");
